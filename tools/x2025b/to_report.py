import re
from openpyxl import load_workbook
wb=load_workbook('비용항목_2025_확정판.xlsx')
del wb['4.방침 점검·원고 확인']
R=[("형사사법 원고(11. 8.)","연구진 형사사법비용 추계(2026)"),("같은 원고","연구진 형사사법비용 추계"),("제3장 원고(11. 6.)","연구진 의료·생산성 추계(2026)"),("제3장 원고","연구진 추계"),("원고 사용값","2024 값"),("원고 값","추계 값"),("원고","연구진 추계"),
   ("교정본부 회신, 2026. 11. 16.","교정본부 자료, 2026. 11."),("교정본부 회신","교정본부 자료"),("미회신","미확정"),("회신","자료"),(" (방침 적용, 11. 14. 수정)","")]
for ws in wb:
    for row in ws.iter_rows():
        for c in row:
            if isinstance(c.value,str) and not c.value.startswith('='):
                v=c.value
                for a,b in R: v=v.replace(a,b)
                c.value=re.sub(r"서식 ?[0-9]+(?:[·,] ?[0-9]+)*","교정본부 자료",v)
wb['0.총괄_2025'].delete_cols(10,2)
for a,b in [('5.1인당 생애비용','4.1인당 생애비용(별지 2)'),('6.추계치 목록','5.추계치 목록'),('7.교정 회신·비용편익(확정)','6.교정 재활 비용편익'),('8.생애가치 비용편익','7.생애가치 비용편익')]: wb[a].title=b
ws=wb['4.1인당 생애비용(별지 2)']; r=ws.max_row+2
ws.cell(r,1,'주'); ws.cell(r,3,'같은 모형을 2016년 기준(박성수, 2018)에 적용한 부가연구(별지 3): 누적 기준(B) 9.82억 원(2016년 가격), 2025년 가격 11.95억 원. 작은 주된 이유는 가격 기준, 1년차 원단위(사망 고통 2.81억 원, 사회적 혼란 미산정)')
wb.save('비용항목_2025_보고용.xlsx')
