def table(ws, title, sub, heads, widths, rows, status_col=None):
    ws.sheet_view.showGridLines = False
    ws['A1'] = title; ws['A1'].font = Font(name=F, size=13, bold=True)
    ws['A2'] = sub; ws['A2'].font = Font(name=F, size=9, color='FF595959')
    for j, (h, w) in enumerate(zip(heads, widths), 1):
        c = ws.cell(4, j, h); c.font = Font(name=F, size=9, bold=True, color='FFFFFFFF'); c.fill = HDR
        c.alignment = Alignment(wrap_text=True, vertical='center', horizontal='center'); c.border = BOX
        ws.column_dimensions[c.column_letter].width = w
    for i, rw in enumerate(rows, 5):
        for j, v in enumerate(rw, 1):
            c = ws.cell(i, j, v); c.font = Font(name=F, size=9)
            c.alignment = Alignment(wrap_text=True, vertical='top'); c.border = BOX
        if status_col:
            st = rw[status_col - 1]
            for k, col in FILL.items():
                if st.startswith(k):
                    ws.cell(i, status_col).fill = PatternFill('solid', fgColor=col)
                    ws.cell(i, status_col).font = Font(name=F, size=9, bold=True)
    ws.freeze_panes = 'C5'


